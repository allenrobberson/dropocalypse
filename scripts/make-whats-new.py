#!/usr/bin/env python3
"""Turns docs/whats-new.md into the notes the app shows in its "What's New" window.

    python3 scripts/make-whats-new.py            rewrite the generated files
    python3 scripts/make-whats-new.py --check    fail if they are out of date (CI)
    python3 scripts/make-whats-new.py --has 1.4.0  fail if that version has no section (release)

Writes Sources/Dropocalypse/WhatsNewNotes.swift (Mac) and windows/src/whats_new_notes.h
(Windows and Linux).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "docs", "whats-new.md")
SWIFT = os.path.join(ROOT, "Sources", "Dropocalypse", "WhatsNewNotes.swift")
CPP = os.path.join(ROOT, "windows", "src", "whats_new_notes.h")
HEADER = "Generated by scripts/make-whats-new.py from docs/whats-new.md. Edit that file, not this one."


def parse():
    text = open(SOURCE, encoding="utf-8").read()
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    entries, current = [], None
    for raw in text.splitlines():
        line = raw.rstrip()
        m = re.match(r"^##\s+(\d+(?:\.\d+)+)\s*$", line)
        if m:
            current = (m.group(1), [])
            entries.append(current)
        elif line.startswith("- "):
            if current is None:
                sys.exit("whats-new.md: a bullet comes before the first '## x.y.z' heading")
            current[1].append(line[2:].strip())
        elif line.startswith("  ") and current and current[1]:
            current[1][-1] += " " + line.strip()   # wrapped bullet
    for version, items in entries:
        if not items:
            sys.exit(f"whats-new.md: {version} has no bullets")
    return entries


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def split_title(item):
    """'**Title.** rest' -> ('Title.', 'rest'); otherwise ('', item without ** markers)."""
    m = re.match(r"^\*\*(.+?)\*\*\s*(.*)$", item)
    if m:
        return m.group(1), m.group(2).replace("**", "")
    return "", item.replace("**", "")


def swift_source(entries):
    out = [f"// {HEADER}", "", "enum WhatsNewNotes {",
           "    /// Newest first. Each bullet may use **bold** (rendered as Markdown).",
           "    static let entries: [(version: String, items: [String])] = ["]
    for version, items in entries:
        out.append(f'        ("{version}", [')
        for it in items:
            out.append(f'            "{esc(it)}",')
        out.append("        ]),")
    out += ["    ]", "}", ""]
    return "\n".join(out)


def cpp_source(entries):
    out = [f"// {HEADER}", "#pragma once", "", "struct WhatsNewItem { const char* title; const char* body; };",
           "struct WhatsNewEntry { const char* version; const WhatsNewItem* items; int count; };", ""]
    for i, (version, items) in enumerate(entries):
        out.append(f"inline const WhatsNewItem kWhatsNewItems{i}[] = {{")
        for it in items:
            title, body = split_title(it)
            out.append(f'    {{"{esc(title)}", "{esc(body)}"}},')
        out.append("};")
    out.append("")
    out.append("// Newest first.")
    out.append("inline const WhatsNewEntry kWhatsNew[] = {")
    for i, (version, items) in enumerate(entries):
        out.append(f'    {{"{version}", kWhatsNewItems{i}, {len(items)}}},')
    out.append("};")
    out.append(f"inline constexpr int kWhatsNewCount = {len(entries)};")
    out.append("")
    return "\n".join(out)


def main():
    entries = parse()
    if len(sys.argv) > 2 and sys.argv[1] == "--has":
        want = sys.argv[2].lstrip("v")
        if want not in [v for v, _ in entries]:
            sys.exit(f"docs/whats-new.md has no '## {want}' section. Add what's new in {want} for the "
                     f"app's What's New window, then run python3 scripts/make-whats-new.py and commit.")
        print(f"whats-new.md has {want}")
        return
    files = {SWIFT: swift_source(entries), CPP: cpp_source(entries)}
    if "--check" in sys.argv:
        stale = [p for p, s in files.items()
                 if not os.path.exists(p) or open(p, encoding="utf-8").read() != s]
        if stale:
            sys.exit("Out of date: " + ", ".join(os.path.relpath(p, ROOT) for p in stale) +
                     ". Run python3 scripts/make-whats-new.py and commit.")
        print("What's New notes are up to date")
        return
    for path, s in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(s)
        print("wrote", os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
