#!/usr/bin/env python3
"""Embeds the bundled MilkDrop presets and textures (milkdrop/presets, milkdrop/textures) into
windows/src/milkdrop_bundled.h, for the Windows and Linux apps. They write them to the app's data
folder on start, so in-app updates (which replace only the program files) bring new presets too.
The Mac app copies the same folder into its bundle instead (scripts/build-app.sh).

    python3 scripts/make-milkdrop-bundle.py          # rewrite the header
    python3 scripts/make-milkdrop-bundle.py --check  # fail if it is out of date (CI)
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "milkdrop"
OUT = ROOT / "windows" / "src" / "milkdrop_bundled.h"

files = sorted(p for d in ("presets", "textures") for p in (SRC / d).iterdir() if p.is_file())
parts = ["// GENERATED by scripts/make-milkdrop-bundle.py from the milkdrop/ folder. Do not edit.\n"
         "#pragma once\n\n#include <cstddef>\n\nstruct BundledMilkFile {\n"
         "    const char* path;          // relative, with forward slashes\n"
         "    const unsigned char* data;\n    size_t size;\n};\n\n"]
for i, p in enumerate(files):
    data = p.read_bytes()
    rows = [", ".join(f"0x{b:02x}" for b in data[j:j + 20]) for j in range(0, len(data), 20)]
    parts.append(f"static const unsigned char kMilkFile{i}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n")
parts.append("\nstatic const BundledMilkFile kBundledMilkFiles[] = {\n")
for i, p in enumerate(files):
    rel = p.relative_to(SRC).as_posix().replace('"', '\\"')
    parts.append(f'    {{"{rel}", kMilkFile{i}, sizeof(kMilkFile{i})}},\n')
parts.append("};\n")
text = "".join(parts)

if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("milkdrop_bundled.h is out of date: run python3 scripts/make-milkdrop-bundle.py")
    print("milkdrop_bundled.h is up to date")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(files)} files)")
