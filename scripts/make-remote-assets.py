#!/usr/bin/env python3
"""Embeds the phone remote page and the shared option schema into shared/remote/remote_assets.h,
which the Mac, Windows and Linux apps all compile (through shared/remote/remote_server.cpp).

    python3 scripts/make-remote-assets.py           # regenerate after editing page.html / schema.json
    python3 scripts/make-remote-assets.py --check   # CI: fail if the header is out of date
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
DIR = ROOT / "shared" / "remote"
OUT = DIR / "remote_assets.h"


def array(name, data):
    data = data + b"\0"
    rows = []
    for i in range(0, len(data), 24):
        rows.append("    " + ",".join(str(b - 256 if b > 127 else b) for b in data[i:i + 24]) + ",")
    return f"static const char {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def build():
    page = (DIR / "page.html").read_bytes()
    schema = json.loads((DIR / "schema.json").read_text())
    compact = json.dumps(schema, separators=(",", ":"), ensure_ascii=False).encode()
    return ("// GENERATED by scripts/make-remote-assets.py from shared/remote/page.html and schema.json.\n"
            "// Edit those files and run the script instead of editing this one.\n"
            "#pragma once\n\n" + array("kRemotePage", page) + "\n" + array("kRemoteSchema", compact))


text = build()
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        sys.exit("shared/remote/remote_assets.h is out of date: run python3 scripts/make-remote-assets.py")
    print("remote assets up to date")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
